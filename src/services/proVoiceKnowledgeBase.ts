/**
 * Pro Multilingual Knowledge Base for Kishan Bhai Voice Assistant
 * Acts like a pro Google AI Assistant with broad agricultural, scientific,
 * mathematical, health, animal husbandry, and general knowledge.
 * 
 * Guarantees strict native-language responses for all 11 Indian languages + English:
 * Hindi (hi), Gujarati (gu), Punjabi (pa), Marathi (mr), Bengali (bn),
 * Telugu (te), Tamil (ta), Kannada (kn), Malayalam (ml), Odia (or), Assamese (as), English (en).
 */

export type SupportedLanguage =
  | 'hi'
  | 'gu'
  | 'pa'
  | 'mr'
  | 'bn'
  | 'te'
  | 'ta'
  | 'kn'
  | 'ml'
  | 'or'
  | 'as'
  | 'en';

export function normalizeLang(lang: string | undefined): SupportedLanguage {
  if (!lang) return 'hi';
  const clean = lang.toLowerCase().trim().split(/[-_]/)[0];
  const valid: SupportedLanguage[] = ['hi', 'gu', 'pa', 'mr', 'bn', 'te', 'ta', 'kn', 'ml', 'or', 'as', 'en'];
  if (valid.includes(clean as SupportedLanguage)) {
    return clean as SupportedLanguage;
  }
  return 'hi';
}

export interface AssistantResponseTemplate {
  title: string;
  whyHeader: string;
  whyPoints: string[];
  actionHeader: string;
  actionPoints: string[];
  warningHeader: string;
  warningText: string;
}

export function formatTemplate(t: AssistantResponseTemplate): string {
  const why = t.whyPoints.map((p) => `- ${p}`).join('\n');
  const actions = t.actionPoints.map((p, i) => `${i + 1}. ${p}`).join('\n');
  return `🌱 **${t.title}**\n\n**${t.whyHeader}**\n${why}\n\n**${t.actionHeader}**\n${actions}\n\n⚠️ **${t.warningHeader}** ${t.warningText}`;
}

